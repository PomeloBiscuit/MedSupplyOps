-- =============================================================================
-- MedSupplyOps — 修復 V001 的表／欄位註解（編碼損壞）
--
-- ★ 為什麼需要這支遷移
--
-- V001 於 2026-08-23 套用，而 db/init/02_apply_schema.sh 的 `NLS_LANG=.AL32UTF8`
-- 是 2026-09-01 才補上的。
-- 那之前 sqlplus 用容器 OS 的預設字元集去解讀 UTF-8 的 .sql，
-- 於是 V001 裡的中文註解在寫進資料字典的當下就被換成了 U+FFFD 替代字元。
--
-- `V001__initial_schema.sql` 這個**檔案本身一直是正確的 UTF-8** ——
-- 壞掉的只有資料庫裡那一份。而 V001 從此沒有再被套用過，所以它就一直壞著。
--
-- ★ 為什麼三週都沒有人發現
--
-- 當時修好了成因（NLS_LANG），也補了 SeedDataEncodingTests ——
-- 但那支測試檢查的是**種子資料的列**，不是資料字典裡的註解；
-- ER 圖產生器也不讀註解；註解在 App 畫面上完全看不到。
-- 於是「修好成因」與「修好既有的損壞」之間留下一道縫，
-- 而那道縫沒有任何關卡照得到。
--
-- 這次是備份還原演練（NFR-4）跑 Data Pump 時回報 ORA-39346
-- （字元集轉換遺失）才把它照出來的。
--
-- ★ 這支遷移做什麼
--
-- 重下一次 V001 的全部 COMMENT 敘述。COMMENT ON 是覆寫語意，
-- 重複執行安全；全新安裝時 V001 已經會寫入正確內容，這裡再寫一次也無害。
-- 不動任何資料表結構、索引、約束或資料。
--
-- 另：requisition_lines 的敘述同時改寫，只保留設計理由、拿掉出身描述。
-- V001 的檔案內容已一併對齊，兩者敘述一致，不會產生環境間的漂移。
-- =============================================================================

COMMENT ON TABLE  items                     IS '醫材品項主檔。數量不在此表，在 stock_lots。';
COMMENT ON TABLE  stock_lots                IS '庫存批次。品項+批號+效期+儲位 的唯一組合，數量掛在這裡。';
COMMENT ON COLUMN stock_lots.expiry_date    IS '有效期限。語意為「這一天（含）之前仍可使用」。';
COMMENT ON COLUMN stock_lots.row_version    IS '樂觀並發控制版本號，由應用程式在每次更新時遞增。';
COMMENT ON TABLE  requisition_lines         IS '請領明細。一張請領單可含多個品項，明細獨立成表，才能逐項配批與追溯。';
COMMENT ON TABLE  issue_allocations         IS '發料配批結果，醫材召回追溯的依據。';
COMMENT ON TABLE  audit_logs                IS '稽核軌跡，只增不改不刪。';
